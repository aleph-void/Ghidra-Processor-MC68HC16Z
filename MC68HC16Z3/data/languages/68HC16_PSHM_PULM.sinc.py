"""Generates 68HC16_PSHM_PULM.sinc: one sub-constructor per PSHM/PULM mask value.

    python3 68HC16_PSHM_PULM.sinc.py      (writes 68HC16_PSHM_PULM.sinc next to this file)

CPU16 Reference Manual, PSHM and PULM glossary pages:
  PSHM: for mask bits 0 to 7, if the bit is set, push the register; bit 0 = D, 1 = E, 2 = IX, 3 = IY,
        4 = IZ, 5 = K (EK:XK:YK:ZK), 6 = CCR, 7 reserved.  D is pushed first (highest address).
  PULM: for mask bits 0 to 7, if the bit is set, pull the register; bit 0 = CCR, 1 = K, 2 = IZ,
        3 = IY, 4 = IX, 5 = E, 6 = D, 7 reserved.  CCR is pulled first (lowest address), so PULM
        with the mirrored mask undoes PSHM.
push16/pull16 (68HC16.slaspec) follow the CPU16 convention that SK:SP points to the next free word.
"""
import os

PSHM_REGS = ["D", "E", "IX", "IY", "IZ", "K", "CCR"]
PULM_REGS = ["CCR", "K", "IZ", "IY", "IX", "E", "D"]

PUSH = {
    "D": "push16(D);",
    "E": "push16(E);",
    "IX": "push16(IX);",
    "IY": "push16(IY);",
    "IZ": "push16(IZ);",
    "K": "local kw:2 = (zext(EK & 0x0F) << 12) | (zext(XK & 0x0F) << 8) | (zext(YK & 0x0F) << 4) | zext(ZK & 0x0F); push16(kw);",
    "CCR": "local cw:2; ccrWord(cw); push16(cw);",
}
PULL = {
    "D": "pull16(D);",
    "E": "pull16(E);",
    "IX": "pull16(IX);",
    "IY": "pull16(IY);",
    "IZ": "pull16(IZ);",
    "K": "local kw:2; pull16(kw); EK = kw(1) >> 4; XK = kw(1) & 0x0F; YK = kw:1 >> 4; ZK = kw:1 & 0x0F;",
    "CCR": "local cw:2; pull16(cw); CCR = (cw & 0xFFF0) | (CCR & 0x000F);",
}


def generate(filename):
    with open(filename, "w") as f:
        f.write("# 68HC16 PSHM/PULM register lists (generated by 68HC16_PSHM_PULM.sinc.py; do not edit)\n\n")
        f.write("# --- PSHM: mask bit 0 = D ... bit 6 = CCR; pushed in bit order (D first) ---\n")
        for i in range(256):
            regs = [PSHM_REGS[b] for b in range(7) if (i >> b) & 1]
            body = " ".join(PUSH[r] for r in regs)
            f.write(f'pshmList: "{",".join(regs)}" is regmask=0x{i:02X} {{ {body} }}\n')
        f.write("\n# --- PULM: mask bit 0 = CCR ... bit 6 = D; pulled in bit order (CCR first) ---\n")
        for i in range(256):
            regs = [PULM_REGS[b] for b in range(7) if (i >> b) & 1]
            body = " ".join(PULL[r] for r in regs)
            f.write(f'pulmList: "{",".join(regs)}" is regmask=0x{i:02X} {{ {body} }}\n')


if __name__ == "__main__":
    generate(os.path.join(os.path.dirname(os.path.abspath(__file__)), "68HC16_PSHM_PULM.sinc"))
